    /**
     * Excel serial (integer) أو نص تاريخ يقبله Carbon ➜ Carbon|null
     */
    private function excelDateToCarbon($value)
    {
        $value = trim((string)$value);
        if ($value === '') return null;

        if (is_numeric($value)) {
            try {
                return \Carbon\Carbon::createFromTimestampUTC(((int)$value - 25569) * 86400);
            } catch (\Exception) {
                return null;
            }
        }

        try {
            return \Carbon\Carbon::parse($value);
        } catch (\Exception) {
            return null;
        }
    }

    /**
     * يحول القيم الفارغة إلى NULL حفاظاً على سلامة قاعدة البيانات.
